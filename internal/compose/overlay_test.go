func TestOverlayPorts(t *testing.T) {
	got := string(Overlay{Ports: map[string][]Port{
		"web": {{Target: 80, Published: "8081", HostIP: "127.0.0.1", Protocol: "tcp"}, {Target: 53, Published: "5353", Protocol: "udp", Mode: "host"}},
		"api": {{Target: 3000, Published: "3304"}},
	}}.Render())
	want := `services:
  "api":
    ports: !override
      - target: 3000
        published: "3304"
  "web":
    ports: !override
      - target: 80
        published: "8081"
        host_ip: "127.0.0.1"
        protocol: "tcp"
      - target: 53
        published: "5353"
        protocol: "udp"
        mode: "host"
`
	if !strings.HasSuffix(got, want) || !strings.HasPrefix(got, "# Generated by Theo") {
		t.Errorf("overlay:\n%s", got)
	}
}

func TestDefaultFiles(t *testing.T) {
	dir := t.TempDir()
	if got := DefaultFiles(dir); got != nil {
		t.Errorf("empty dir: %v", got)
	}
	for _, f := range []string{"docker-compose.yml", "docker-compose.override.yml", "compose.yaml"} {
		if err := os.WriteFile(filepath.Join(dir, f), nil, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	// compose.yaml wins and has no override: the docker-compose ones are ignored.
	if got, want := DefaultFiles(dir), []string{filepath.Join(dir, "compose.yaml")}; !reflect.DeepEqual(got, want) {
		t.Errorf("got %v, want %v", got, want)
	}
	os.Remove(filepath.Join(dir, "compose.yaml"))
	want := []string{filepath.Join(dir, "docker-compose.yml"), filepath.Join(dir, "docker-compose.override.yml")}
	if got := DefaultFiles(dir); !reflect.DeepEqual(got, want) {
		t.Errorf("got %v, want %v", got, want)
	}
}

func TestTargetArgsPutFilesFirst(t *testing.T) {
	got := Target{Name: "p", Files: []string{"a.yaml", "b.yaml"}, EnvFiles: []string{"e"}}.args(nil, "up")
	want := []string{"compose", "-p", "p", "-f", "a.yaml", "-f", "b.yaml", "--env-file", "e", "up"}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("args = %v", got)
	}
}

func TestOverlayContainerNamesAndEnvironment(t *testing.T) {
	o := Overlay{
		ResetContainerName: []string{"db"},
		Environment:        map[string]map[string]string{"api": {"B": "x\"y\nz", "A": "1"}, "db": {"C": "3"}},
	}
	got := string(o.Render())
	want := `services:
  "api":
    environment:
      "A": "1"
      "B": "x\"y\nz"
  "db":
    container_name: !reset null
    environment:
      "C": "3"
`
	if !strings.HasSuffix(got, want) {
		t.Errorf("overlay:\n%s", got)
	}
	if (Overlay{}).Empty() == false || o.Empty() {
		t.Errorf("Empty is wrong")
	}
}

func TestOverlaySharedServices(t *testing.T) {
	o := Overlay{
		ExternalNetworks: map[string]string{"theo_shared": "theo-app-shared"},
		Profiles:         map[string][]string{"db": {"theo-shared"}},
		DependsOn: map[string]map[string]json.RawMessage{
			"api":    {"cache": json.RawMessage(`{"condition":"service_started","required":true}`)},
			"worker": {},
		},
		Networks: map[string][]string{"api": {"default", "theo_shared"}},
		Ports:    map[string][]Port{"db": {}},
	}
	got := string(o.Render())
	want := `networks:
  "theo_shared":
    external: true
    name: "theo-app-shared"
services:
  "api":
    depends_on: !override
      "cache": {"condition":"service_started","required":true}
    networks:
      "default": {}
      "theo_shared": {}
  "db":
    ports: !override []
    profiles: !override
      - "theo-shared"
  "worker":
    depends_on: !reset null
`
	if !strings.HasSuffix(got, want) {
		t.Errorf("overlay:\n%s", got)
	}
	if o.Empty() || !(Overlay{}).Empty() {
		t.Errorf("Empty is wrong")
	}
}
