// defaultFileNames are the Compose files `docker compose` looks for, in
// order of preference.
var defaultFileNames = []string{"compose.yaml", "compose.yml", "docker-compose.yaml", "docker-compose.yml"}

// DefaultFiles returns the files `docker compose` loads by itself in dir:
// the first of compose.yaml, compose.yml, docker-compose.yaml and
// docker-compose.yml, and its override file when it exists. It is empty when
// there is none. Passing an extra file with -f turns this discovery off, so
// Theo needs the list to add its own file.
func DefaultFiles(dir string) []string {
	for _, name := range defaultFileNames {
		base := filepath.Join(dir, name)
		if !isFile(base) {
			continue
		}
		files := []string{base}
		ext := filepath.Ext(name)
		override := filepath.Join(dir, strings.TrimSuffix(name, ext)+".override"+ext)
		if isFile(override) {
			files = append(files, override)
		}
		return files
	}
	return nil
}

func isFile(path string) bool {
	info, err := os.Stat(path)
	return err == nil && info.Mode().IsRegular()
}

// RenderPortsOverlay renders a Compose file that replaces the published
// ports of the given services (service name to its complete list of ports,
// since Compose would otherwise add to the original ones). The output is
// deterministic. It needs Compose 2.24.4 or later for the !override tag.
func RenderPortsOverlay(ports map[string][]Port) []byte {
	var b strings.Builder
	b.WriteString("# Generated by Theo. It replaces published host ports for this instance only;\n# your Compose files are not modified. Safe to delete: Theo regenerates it.\nservices:\n")
	for _, svc := range SortedKeys(ports) {
		fmt.Fprintf(&b, "  %s:\n    ports: !override\n", quote(svc))
		for _, p := range ports[svc] {
			fmt.Fprintf(&b, "      - target: %d\n", p.Target)
			if p.Published != "" {
				fmt.Fprintf(&b, "        published: %s\n", quote(p.Published))
			}
			if p.HostIP != "" {
				fmt.Fprintf(&b, "        host_ip: %s\n", quote(p.HostIP))
			}
			if p.Protocol != "" {
				fmt.Fprintf(&b, "        protocol: %s\n", quote(p.Protocol))
			}
			if p.Mode != "" {
				fmt.Fprintf(&b, "        mode: %s\n", quote(p.Mode))
			}
		}
	}
	return []byte(b.String())
}

func quote(s string) string {
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(s) + `"`
}

// ConfigFor returns the configuration of the project as it would run with
// the target's name, env files and Compose files.
func (Compose) ConfigFor(ctx context.Context, t Target) (*Project, error) {
	out, err := execx.Run(ctx, t.Dir, "docker", t.args([]string{"*"}, "config", "--format", "json")...)
	if err != nil {
		return nil, err
	}
	return ParseConfig(out)
}
