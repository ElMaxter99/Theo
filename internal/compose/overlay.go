// defaultFileNames are the Compose files `docker compose` looks for, in
// order of preference; defaultOverrideNames are its override files, of which
// the first one that exists is loaded, whatever the extension of the base
// file (compose.yaml plus docker-compose.override.yml works). Verified with
// Compose v5.6.1; Theo double-checks the result against Compose itself (see
// Engine.baseComposeFiles).
var (
	defaultFileNames     = []string{"compose.yaml", "compose.yml", "docker-compose.yaml", "docker-compose.yml"}
	defaultOverrideNames = []string{"compose.override.yml", "compose.override.yaml", "docker-compose.override.yml", "docker-compose.override.yaml"}
)

// DefaultFiles returns the files `docker compose` loads by itself in dir:
// the first of compose.yaml, compose.yml, docker-compose.yaml and
// docker-compose.yml, and an override file when one exists. It is empty when
// there is none. Passing an extra file with -f turns this discovery off, so
// Theo needs the list to add its own file.
func DefaultFiles(dir string) []string {
	for _, name := range defaultFileNames {
		base := filepath.Join(dir, name)
		if !isFile(base) {
			continue
		}
		files := []string{base}
		for _, o := range defaultOverrideNames {
			if override := filepath.Join(dir, o); isFile(override) {
				files = append(files, override)
				break
			}
		}
		return files
	}
	return nil
}

func isFile(path string) bool {
	info, err := os.Stat(path)
	return err == nil && info.Mode().IsRegular()
}

// Overlay is what Theo changes for one instance, per service.
type Overlay struct {
	// Ports replaces the published ports of a service; each list is the
	// complete one (possibly empty), since Compose would otherwise add to
	// the original ports.
	Ports map[string][]Port
	// ResetContainerName removes the fixed container_name of a service.
	ResetContainerName []string
	// Environment sets variables in a service, over the ones it has.
	Environment map[string]map[string]string
	// Profiles replaces the profiles of a service. A service whose profile
	// is never enabled does not start.
	Profiles map[string][]string
	// DependsOn replaces the dependencies of a service with the given ones,
	// each as the JSON Compose resolved it. An empty map removes them all.
	DependsOn map[string]map[string]json.RawMessage
	// Networks adds networks to a service. The value is the network key in
	// the Compose file; Default adds the default network explicitly, which a
	// service needs to keep when it joins another network and had none.
	Networks map[string][]string
	// ExternalNetworks declares top-level networks that already exist in
	// Docker: key in the Compose file to Docker name.
	ExternalNetworks map[string]string
}

// Empty reports whether the overlay changes nothing.
func (o Overlay) Empty() bool {
	return len(o.Ports) == 0 && len(o.ResetContainerName) == 0 && len(o.Environment) == 0 &&
		len(o.Profiles) == 0 && len(o.DependsOn) == 0 && len(o.Networks) == 0 && len(o.ExternalNetworks) == 0
}

// Render renders the overlay as a Compose file. The output is deterministic.
// It needs Compose 2.24.4 or later for the !override and !reset tags.
func (o Overlay) Render() []byte {
	services := map[string]bool{}
	for s := range o.Ports {
		services[s] = true
	}
	for _, s := range o.ResetContainerName {
		services[s] = true
	}
	for s := range o.Environment {
		services[s] = true
	}
	for s := range o.Profiles {
		services[s] = true
	}
	for s := range o.DependsOn {
		services[s] = true
	}
	for s := range o.Networks {
		services[s] = true
	}
	reset := map[string]bool{}
	for _, s := range o.ResetContainerName {
		reset[s] = true
	}

	var b strings.Builder
	b.WriteString("# Generated by Theo. It changes this instance only; your Compose files are\n# not modified. It may contain values you set with `theo env`. Safe to delete:\n# Theo regenerates it.\n")
	if len(o.ExternalNetworks) > 0 {
		b.WriteString("networks:\n")
		for _, key := range SortedKeys(o.ExternalNetworks) {
			fmt.Fprintf(&b, "  %s:\n    external: true\n    name: %s\n", quote(key), quote(o.ExternalNetworks[key]))
		}
	}
	if len(services) == 0 {
		return []byte(b.String())
	}
	b.WriteString("services:\n")
	for _, svc := range SortedKeys(services) {
		fmt.Fprintf(&b, "  %s:\n", quote(svc))
		if reset[svc] {
			b.WriteString("    container_name: !reset null\n")
		}
		if deps, ok := o.DependsOn[svc]; ok {
			if len(deps) == 0 {
				b.WriteString("    depends_on: !reset null\n")
			} else {
				b.WriteString("    depends_on: !override\n")
				for _, name := range SortedKeys(deps) {
					fmt.Fprintf(&b, "      %s: %s\n", quote(name), strings.TrimSpace(string(deps[name])))
				}
			}
		}
		if env := o.Environment[svc]; len(env) > 0 {
			b.WriteString("    environment:\n")
			for _, k := range SortedKeys(env) {
				// Compose interpolates the values of its files: a literal $ is $$.
				fmt.Fprintf(&b, "      %s: %s\n", quote(k), quote(strings.ReplaceAll(env[k], "$", "$$")))
			}
		}
		if nets := o.Networks[svc]; len(nets) > 0 {
			b.WriteString("    networks:\n")
			for _, n := range nets {
				fmt.Fprintf(&b, "      %s: {}\n", quote(n))
			}
		}
		if ports, ok := o.Ports[svc]; ok {
			if len(ports) == 0 {
				b.WriteString("    ports: !override []\n")
			} else {
				b.WriteString("    ports: !override\n")
			}
			for _, p := range ports {
				fmt.Fprintf(&b, "      - target: %d\n", p.Target)
				if p.Published != "" {
					fmt.Fprintf(&b, "        published: %s\n", quote(p.Published))
				}
				if p.HostIP != "" {
					fmt.Fprintf(&b, "        host_ip: %s\n", quote(p.HostIP))
				}
				if p.Protocol != "" {
					fmt.Fprintf(&b, "        protocol: %s\n", quote(p.Protocol))
				}
				if p.Mode != "" {
					fmt.Fprintf(&b, "        mode: %s\n", quote(p.Mode))
				}
			}
		}
		if profiles, ok := o.Profiles[svc]; ok {
			b.WriteString("    profiles: !override\n")
			for _, p := range profiles {
				fmt.Fprintf(&b, "      - %s\n", quote(p))
			}
		}
	}
	return []byte(b.String())
}

// quote returns s as a YAML double-quoted string.
func quote(s string) string {
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`, "\n", `\n`, "\r", `\r`, "\t", `\t`).Replace(s) + `"`
}

// ConfigText returns the resolved configuration of the project as Compose
// prints it (YAML), as it would run with the target's name, env files and
// Compose files.
func (Compose) ConfigText(ctx context.Context, t Target) ([]byte, error) {
	args := t.args([]string{"*"}, "config")
	if execx.Explaining() && !t.filesExist() {
		execx.Describe(t.Dir, "docker", args...) // --explain did not write the generated files
		return nil, nil
	}
	return execx.Run(ctx, t.Dir, "docker", args...)
}

// ConfigFor returns the configuration of the project as it would run with
// the target's name, env files and Compose files.
func (Compose) ConfigFor(ctx context.Context, t Target) (*Project, error) {
	out, err := execx.Run(ctx, t.Dir, "docker", t.args([]string{"*"}, "config", "--format", "json")...)
	if err != nil {
		return nil, err
	}
	return ParseConfig(out)
}

// filesExist reports whether the Compose and env files of the target exist.
func (t Target) filesExist() bool {
	for _, f := range append(append([]string(nil), t.Files...), t.EnvFiles...) {
		if _, err := os.Stat(f); err != nil {
			return false
		}
	}
	return true
}
