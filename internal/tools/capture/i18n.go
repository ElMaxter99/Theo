// Tr returns the text of key in lang, formatted with args. A missing key in
// Spanish falls back to English, and a missing key everywhere is returned as
// is so the mistake is visible.
func Tr(lang, key string, args ...any) string {
	s, ok := catalog[lang][key]
	if !ok {
		if s, ok = catalog[LangEN][key]; !ok {
			return key
		}
	}
	if len(args) == 0 {
		return s
	}
	return fmt.Sprintf(s, args...)
}
