// Languages the reports come out in. The language is Theo's own: the
// `language` preference, the interface language when the interface asks for
// a report, or the system's. A report text is never written inside a
// template: it is a key of this catalog.
const (
	LangEN = "en"
	LangES = "es"
)

// ResolveLang picks the language of a report: an explicit choice, then the
// preference, then the system's (LC_ALL, LANG), then English.
func ResolveLang(explicit, pref string) string {
	for _, c := range []string{explicit, pref, os.Getenv("LC_ALL"), os.Getenv("LANG")} {
		c = strings.ToLower(strings.TrimSpace(c))
		switch {
		case strings.HasPrefix(c, "es"):
			return LangES
		case strings.HasPrefix(c, "en"):
			return LangEN
		}
	}
	return LangEN
}

